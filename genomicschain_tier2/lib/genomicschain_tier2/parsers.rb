# frozen_string_literal: true

require 'yaml'
# `Date` is named in safe_yaml's permitted_classes. Whether `require 'yaml'`
# happens to load it depends on the psych version (it does not on Ruby 3.2.3),
# and without it every YAML file silently parsed as nothing. Load it here.
require 'date'
require_relative 'pin_strength'

module GenomicsChainTier2
  # One parser per declaration grammar. Each returns a flat list of declaration
  # hashes; none of them judges anything.
  #
  # Every parser is line-anchored — a declaration carries the file and line it
  # came from, so a finding can always be walked back to the bytes that produced
  # it. This is not a nicety. The pilot that motivated this whole layer reported
  # "13 of 30 steps demoted" and the step indices were never written down, so
  # the finding cannot now be re-derived. A scan whose output cannot be checked
  # against its input reproduces exactly the failure it exists to detect.
  module Parsers
    module_function

    # `workflow/envs/*.yaml`, `environment.yml` — a conda environment file.
    def conda_env(rel, text)
      doc = safe_yaml(text)
      return [] unless doc.is_a?(Hash) && doc['dependencies'].is_a?(Array)

      flatten_deps(doc['dependencies']).map do |spec|
        level, reason = PinStrength.conda_spec(spec)
        decl(kind: 'software_env', name: spec.to_s.split(/[=<>~!\s]/).first, locator: spec.to_s,
             pin: level, reason: reason, source: rel, line: line_of(text, spec.to_s))
      end
    end

    # `conda-lock` output. Every line of an @EXPLICIT block is a URL carrying the
    # package's md5, which is the strongest pin conda produces. A scanner that
    # reads only `envs/*.yaml` and skips these files reports "nothing is pinned"
    # about a repository that pinned its software completely — a false finding of
    # exactly the kind this layer is supposed to make impossible.
    def conda_lock(rel, text)
      return [] unless text.include?('@EXPLICIT') || text.include?('Generated by conda-lock')

      text.each_line.with_index(1).filter_map do |line, no|
        url = line.strip
        next unless url =~ %r{\Ahttps?://}

        pkg = url.split('/').last.to_s.split('#').first
        decl(kind: 'software_env', name: pkg, locator: url,
             pin: url.include?('#') ? 'immutable' : 'floating',
             reason: url.include?('#') ? 'conda-lock URL carrying the package md5' : 'lock line without a hash',
             source: rel, line: no)
      end
    end

    # A Snakemake `container:` directive, at workflow or rule level.
    def snakemake(rel, text)
      text.each_line.with_index(1).filter_map do |line, no|
        next if line.strip.start_with?('#')
        m = line.match(/^\s*container:\s*(.+?)\s*$/)
        next unless m

        level, reason = PinStrength.container(m[1])
        decl(kind: 'container', name: 'container', locator: m[1].gsub(/\A["']|["']\z/, ''),
             pin: level, reason: reason, source: rel, line: no)
      end
    end

    # Snakemake rule blocks, and the configuration keys each one reads.
    #
    # This is what makes a per-step verdict possible instead of a per-repository
    # one. The rubric assigns `env_capture_class` per step, so an adjudicator
    # needs to know which step consumes which resource; `rule X:` ... `config["y"]`
    # gives exactly that, by indentation, without evaluating anything.
    #
    # Blocks end at the next line with no leading whitespace, which is how
    # Snakemake's own grammar delimits them.
    def snakemake_rules(rel, text)
      rules = []
      current = nil
      indent = 0

      text.each_line.with_index(1) do |line, no|
        # A rule may be indented: aMeta declares `rule NCBIMapTre` twice, once
        # inside each branch of an `if snakemake_version >= 8` conditional. A
        # parser anchored at column 0 misses both, and both fetch a rolling
        # master-branch URL — the exact class of resource the rubric calls fatal.
        if (m = line.match(/^(\s*)(rule|checkpoint)\s+([A-Za-z_]\w*)\s*:/))
          indent = m[1].length
          current = { rule: m[3], kind: m[2], source: rel, line: no,
                      config_keys: [], urls: [] }
          rules << current
          next
        end

        # The block ends at the next non-blank line indented no deeper than the
        # `rule` keyword itself.
        current = nil if current && line =~ /\S/ && line[/\A\s*/].length <= indent
        next unless current

        line.scan(/config\[\s*["']([^"']+)["']\s*\]/) { |k| current[:config_keys] << k.first }
        line.scan(PinStrength::URL_ANY) { |u| current[:urls] << u }
      end

      rules.each do |r|
        r[:config_keys] = r[:config_keys].uniq
        r[:urls] = r[:urls].uniq
      end

      # A name declared more than once is version- or platform-conditional, and
      # which variant runs cannot be known without evaluating the workflow. Say
      # so rather than silently keeping the last one.
      dupes = rules.group_by { |r| r[:rule] }.select { |_, v| v.length > 1 }.keys
      rules.each { |r| r[:conditionally_redeclared] = true if dupes.include?(r[:rule]) }
      rules
    end

    def dockerfile(rel, text)
      text.each_line.with_index(1).filter_map do |line, no|
        m = line.match(/^\s*FROM\s+(\S+)/i)
        next unless m

        level, reason = PinStrength.container(m[1])
        decl(kind: 'container', name: 'FROM', locator: m[1], pin: level, reason: reason,
             source: rel, line: no)
      end
    end

    # Any other YAML: take every string leaf shaped like a locator. `root` is
    # passed so a path can be checked for presence in the repository — a path
    # that ships alongside the code is a different fact from one that does not,
    # and the difference is observable rather than inferred.
    def config_yaml(rel, text, root)
      doc = safe_yaml(text)
      return [] unless doc.is_a?(Hash) || doc.is_a?(Array)

      leaves(doc).filter_map do |key, value|
        next unless PinStrength.locator_shaped?(value, key)

        level, reason = PinStrength.data_locator(value)
        d = decl(kind: 'data', name: key, locator: value, pin: level, reason: reason,
                 source: rel, line: line_of(text, value))
        d[:present_in_repo] = File.exist?(File.join(root, value)) if level == 'local_path'
        d
      end
    end

    # Locators that appear in prose or in a comment. These are NOT declarations
    # — nothing reads them — which is the entire point of collecting them
    # separately. A DOI in a comment and the same DOI in a config value are the
    # same characters and completely different facts.
    def prose_locators(rel, text)
      commentary = if rel =~ /\.(md|rst|txt)\z/i
                     text
                   else
                     text.each_line.select { |l| l.strip.start_with?('#') }.join
                   end
      PinStrength.locators_in(commentary).map do |loc|
        { locator: loc, source: rel, line: line_of(text, loc) }
      end
    end

    # --- helpers ---

    def decl(kind:, name:, locator:, pin:, reason:, source:, line:)
      { kind: kind, name: name.to_s, locator: locator.to_s, pin: pin,
        reason: reason, source: source, line: line }
    end

    # Only YAML's own errors are swallowed. Anything else (a missing constant,
    # a bug) propagates: on Ruby 3.2.3 a NameError here was rescued as
    # `StandardError`, every YAML file parsed as nothing, and the scan reported
    # a clean repository with the same evidence digest as a correct run.
    def safe_yaml(text)
      YAML.safe_load(text, aliases: true, permitted_classes: [Date, Time])
    rescue Psych::Exception
      nil # a file we cannot parse is listed in target.files_unparsed, never guessed at
    end

    # :ok | :unparseable — so the Scanner can record a parse failure instead of
    # letting it look like a file that declares nothing.
    def yaml_status(text)
      YAML.safe_load(text, aliases: true, permitted_classes: [Date, Time])
      :ok
    rescue Psych::Exception
      :unparseable
    end

    # conda allows `- pip:` sub-lists; flatten them into plain spec strings.
    def flatten_deps(list)
      list.flat_map do |entry|
        case entry
        when String then [entry]
        when Hash   then entry.flat_map { |k, v| Array(v).map { |x| "#{k}:#{x}" } }
        else []
        end
      end
    end

    # Walk a parsed document to its string leaves, remembering the dotted key.
    def leaves(node, prefix = nil, acc = [])
      case node
      when Hash  then node.each { |k, v| leaves(v, [prefix, k].compact.join('.'), acc) }
      when Array then node.each_with_index { |v, i| leaves(v, "#{prefix}[#{i}]", acc) }
      else acc << [prefix.to_s, node]
      end
      acc
    end

    def line_of(text, needle)
      return nil if needle.to_s.empty?

      idx = text.each_line.find_index { |l| l.downcase.include?(needle.to_s.downcase) }
      idx ? idx + 1 : nil
    end
  end
end
