# frozen_string_literal: true

# The library half needs no gem and no network: every case builds its own
# repository in a tmpdir. The three scenarios that end in `_regression` are the
# false positives the first run against a real repository (NBISweden/aMeta,
# 2026-09-01) actually produced; they are here so that widening a parser cannot
# quietly bring them back.
require 'minitest/autorun'
require 'tmpdir'
require 'fileutils'

$LOAD_PATH.unshift(File.expand_path('../lib', __dir__))
require 'genomicschain_tier2'

class CodescanTest < Minitest::Test
  P = GenomicsChainTier2::PinStrength

  # --- the rubric ---

  def test_container_levels
    assert_equal 'immutable', P.container("docker://img@sha256:#{'a' * 64}").first
    assert_equal 'versioned', P.container('docker://continuumio/miniconda3:4.12.0').first
    assert_equal 'floating',  P.container('docker://continuumio/miniconda3:latest').first
    # aMeta's actual directive: no tag at all.
    assert_equal 'floating',  P.container('docker://continuumio/miniconda3').first
    assert_match(/no tag at all/, P.container('docker://continuumio/miniconda3').last)
  end

  # A registry port is a colon that is not a tag.
  def test_registry_port_is_not_read_as_a_tag
    assert_equal 'floating', P.container('registry.example:5000/img').first
    assert_equal 'versioned', P.container('registry.example:5000/img:2.1').first
  end

  def test_conda_spec_levels
    assert_equal 'floating',  P.conda_spec('pandas').first
    assert_equal 'ranged',    P.conda_spec('python>=3.10,<3.12').first
    assert_equal 'ranged',    P.conda_spec('fastqc>=0.12.1').first
    assert_equal 'versioned', P.conda_spec('samtools=1.17').first
    assert_equal 'versioned', P.conda_spec('samtools=1.17=h6899075_1').first
  end

  # `pip` is both the marker for a conda `pip:` sub-list AND an ordinary conda
  # package that nearly every exported environment lists. Matching the bare
  # prefix classified the package form — name=version=build, the strongest pin
  # conda offers — as an unpinned pip requirement, and biased the count toward
  # "unpinned", which is the direction that changes a readiness score.
  # Measured on Plasmid-Fiber-seq (2026-09-08): 2 of 420 declarations.
  def test_conda_pip_package_is_not_mistaken_for_a_pip_requirement
    assert_equal 'versioned', P.conda_spec('pip=24.2=pyh8b19718_1').first
    assert_equal 'versioned', P.conda_spec('pip=24.0').first
    assert_equal 'versioned', P.conda_spec('pipx=1.7.1=pyhd8ed1ab_0').first

    # The sub-list form still classifies as before: `==` without a hash does not
    # fix which wheel is installed.
    level, reason = P.conda_spec('pip:seaborn==0.13.2')
    assert_equal 'floating', level
    assert_match(/pip requirement/, reason)
  end

  def test_data_locator_levels
    assert_equal 'local_path', P.data_locator('resources/krakendb').first
    assert_equal 'floating',   P.data_locator('https://example.org/db.tar.gz').first
    assert_equal 'versioned',  P.data_locator('https://doi.org/10.17044/scilifelab.20518251').first
    assert_equal 'immutable',  P.data_locator("db.tar.gz sha256:#{'b' * 64}").first
  end

  # --- what is not a locator (regressions from the first real run) ---

  def test_json_schema_pointer_is_not_a_locator_regression
    refute P.locator_shaped?('#/definitions/analyses')
    refute P.locator_shaped?('http://json-schema.org/draft/2020-12/schema', 'properties.x.$schema')
    refute P.locator_shaped?('definitions/envmodule', 'properties.envmodules.properties.r.$ref')
  end

  def test_glob_is_not_a_locator_regression
    refute P.locator_shaped?('*fastqc*')
    refute P.locator_shaped?('results/*/qc.txt')
  end

  def test_ordinary_scalars_are_not_locators
    refute P.locator_shaped?('32G')
    refute P.locator_shaped?('a sentence with spaces / and a slash')
    refute P.locator_shaped?('')
    refute P.locator_shaped?(1000)
    assert P.locator_shaped?('resources/krakendb')
    assert P.locator_shaped?('samples.tsv')
  end

  # --- end to end, on a repository shaped like the real one ---

  def test_ameta_shaped_repository_produces_the_expected_findings
    in_repo do |root|
      write(root, 'workflow/Snakefile', %(configfile: "config/config.yaml"\ncontainer: "docker://continuumio/miniconda3"\n))
      write(root, 'config/config.yaml', <<~YAML)
        samplesheet: "config/samples.tsv"
        krakenuniq_db: resources/krakendb
        ncbi_db: resources/ncbi
        krakenuniq_preload_size: "32G"
        n_tax_reads: 200
      YAML
      write(root, 'config/samples.tsv', "sample\tfq\n")
      write(root, 'workflow/envs/krakenuniq.yaml', "channels:\n  - bioconda\ndependencies:\n  - krakenuniq\n  - pandas\n")
      write(root, 'conda-linux-64.lock', <<~LOCK)
        # Generated by conda-lock.
        @EXPLICIT
        https://conda.anaconda.org/conda-forge/linux-64/zlib-1.2.13-h1234567_0.tar.bz2##{'c' * 32}
      LOCK
      write(root, 'README.md', "# aMeta-like\n\n    krakenuniq_db: resources/KrakenUniq_DB\n    # can be downloaded from https://doi.org/10.17044/scilifelab.20518251\n")

      r = scan(root)
      codes = r['findings'].map { |f| f['code'] }

      assert_includes codes, 'container_not_digest_pinned'
      assert_includes codes, 'data_declared_but_not_obtainable'
      assert_includes codes, 'software_pinned_data_not'
      assert_includes codes, 'data_source_named_only_in_prose'

      # samples.tsv ships in the repo and must NOT be counted as unobtainable.
      unobtainable = finding(r, 'data_declared_but_not_obtainable')
      assert_equal 2, unobtainable['evidence_count']
      assert_equal %w[krakenuniq_db ncbi_db], unobtainable['evidence'].map { |e| e[:name] }.sort

      # "32G" and 200 are values, not locations.
      refute(r['declarations'].any? { |d| d[:locator] == '32G' })
    end
  end

  # The finding that motivated the layer: a DOI the prose promises and no
  # machine-read value resolves.
  def test_prose_doi_is_reported_only_when_data_is_unobtainable
    in_repo do |root|
      write(root, 'config/config.yaml', "db: resources/missing\n")
      write(root, 'README.md', "download from https://doi.org/10.17044/scilifelab.20518251\n")
      f = finding(scan(root), 'data_source_named_only_in_prose')
      refute_nil f
      assert(f['evidence'].any? { |e| e[:locator].to_s.include?('10.17044/scilifelab.20518251') })
    end

    # Same README, but the data is right there — no finding.
    in_repo do |root|
      write(root, 'config/config.yaml', "db: resources/present\n")
      write(root, 'resources/present', "x\n")
      write(root, 'README.md', "download from https://doi.org/10.17044/scilifelab.20518251\n")
      assert_nil finding(scan(root), 'data_source_named_only_in_prose')
    end
  end

  # Documentation links are not data-deposit claims and must not be counted as
  # such: the first real run buried 5 real DOIs under 19 badge and homepage URLs.
  def test_documentation_links_do_not_raise_a_prose_finding_regression
    in_repo do |root|
      write(root, 'config/config.yaml', "db: resources/missing\n")
      write(root, 'README.md', <<~MD)
        [![badge](https://img.shields.io/badge/x-y.svg)](https://snakemake.bitbucket.io)
        Install from https://docs.conda.io/en/latest/miniconda.html — see https://github.com/x/y
      MD
      assert_nil finding(scan(root), 'data_source_named_only_in_prose')
    end
  end

  # A repository's test fixture normally holds a copy of the shipped config.
  # Counting both doubles every data finding.
  def test_test_fixtures_are_scoped_out_of_the_headline_regression
    in_repo do |root|
      write(root, 'config/config.yaml', "db: resources/missing\n")
      write(root, '.test/config/config.yaml', "db: resources/missing_too\n")
      r = scan(root)
      assert_equal 1, finding(r, 'data_declared_but_not_obtainable')['evidence_count']
      assert_equal 1, r['counts_in_fixtures']['data']
    end
  end

  def test_lock_file_entries_are_immutable_and_env_files_are_not
    in_repo do |root|
      write(root, 'workflow/envs/e.yaml', "dependencies:\n  - pandas\n")
      write(root, 'conda-linux-64.lock', "@EXPLICIT\nhttps://conda.anaconda.org/x/linux-64/zlib-1.2.13-h0_0.tar.bz2##{'d' * 32}\n")
      r = scan(root)
      assert_equal 1, r['counts_by_kind']['software_env/immutable']
      assert_equal 1, r['counts_by_kind']['software_env/floating']
    end
  end

  # Every claim must be walkable back to the bytes that produced it — the
  # property the pilot this layer replaces did not have.
  def test_every_declaration_is_anchored_to_a_file
    in_repo do |root|
      write(root, 'config/config.yaml', "db: resources/missing\n")
      write(root, 'workflow/Snakefile', %(container: "docker://img"\n))
      scan(root)['declarations'].each do |d|
        refute_nil d[:source], "declaration without a source file: #{d.inspect}"
        refute_nil d[:pin]
        assert_includes P::LEVELS, d[:pin]
      end
    end
  end

  def test_evidence_digest_is_stable_and_content_sensitive
    in_repo do |root|
      write(root, 'config/config.yaml', "db: resources/a\n")
      first = scan(root)['target']['evidence_digest']
      assert_equal first, scan(root)['target']['evidence_digest']

      write(root, 'config/config.yaml', "db: resources/b\n")
      refute_equal first, scan(root)['target']['evidence_digest']
    end
  end

  def test_unparseable_yaml_is_skipped_not_guessed_at
    in_repo do |root|
      write(root, 'config/broken.yaml', "key: [unclosed\n  : :\n")
      write(root, 'config/config.yaml', "db: resources/missing\n")
      r = scan(root) # must not raise
      assert_equal 1, finding(r, 'data_declared_but_not_obtainable')['evidence_count']
      assert_equal ['config/broken.yaml'], r['target']['files_unparsed'],
                   'a parse failure is recorded, not passed off as a file that declares nothing'
    end
  end

  # 2026-09-09: on Ruby 3.2.3 `Date` was not loaded by `require 'yaml'`, the
  # NameError in safe_yaml was rescued as StandardError, and every YAML file
  # parsed as nothing — 11 declarations over 28 papers instead of 2204, with
  # identical evidence digests. Only YAML's own errors may be swallowed.
  def test_only_yaml_errors_are_swallowed
    assert defined?(Date), 'parsers.rb must require date itself'
    assert_equal :unparseable, GenomicsChainTier2::Parsers.yaml_status("key: [unclosed\n  : :\n")
    assert_equal :ok, GenomicsChainTier2::Parsers.yaml_status("a: 1\n")
    assert_raises(NameError) do
      GenomicsChainTier2::Parsers.stub(:safe_yaml, ->(_) { raise NameError, 'uninitialized constant' }) do
        GenomicsChainTier2::Parsers.conda_env('x.yaml', "dependencies: [a]\n")
      end
    end
  end

  # The scan is deterministic given the bytes and the interpreter, so the
  # interpreter is part of the record (author's decision, 2026-09-09).
  def test_toolchain_is_recorded
    in_repo do |root|
      t = scan(root)['target']['toolchain']
      assert_equal RUBY_VERSION, t['ruby']
      assert_equal Psych::VERSION, t['psych']
      assert_equal GenomicsChainTier2::RUBRIC_VERSION, t['codescan_rubric_version']
    end
  end

  def test_empty_directory_yields_no_findings
    in_repo { |root| assert_empty scan(root)['findings'] }
  end

  # --- helpers ---

  def scan(root) = GenomicsChainTier2::Scanner.new(root).scan
  def finding(report, code) = report['findings'].find { |f| f['code'] == code }

  def in_repo
    Dir.mktmpdir('codescan') { |dir| yield dir }
  end

  def write(root, rel, content)
    path = File.join(root, rel)
    FileUtils.mkdir_p(File.dirname(path))
    File.write(path, content)
  end
end
