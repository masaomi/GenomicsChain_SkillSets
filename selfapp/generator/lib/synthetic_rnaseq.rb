# frozen_string_literal: true

# Generator for the fictional RNA-seq subject of the GenomicsChain
# self-application demonstration (docs/design/self_application_design_v0_1.md
# §4, unit S1). Standard library only; everything is drawn from one
# Random.new(seed) (MT19937) in a fixed order, so the same seed, generator and
# Ruby version give byte-identical output.
#
# Nothing here is real: every identifier is from the SYN/SYNT/SYNTH-S/SynthRef
# scheme, every human-facing file carries NOTICE, and the answer key (which
# genes were made differentially expressed) is written OUTSIDE the subject.

require 'digest'
require 'erb'
require 'fileutils'
require 'json'
require 'stringio'
require 'zlib'

module SyntheticRnaseq
  NOTICE = 'SYNTHETIC — FICTIONAL STUDY. Generated by GenomicsChain self-application generator; ' \
           'not real data, not a real study.'
  GENERATOR_VERSION = '0.1.0'
  SUBJECT_DIR = 'synthetic_rnaseq_v1'
  TRUTH_FILE = 'synthetic_truth_v1.json'
  REFERENCE_RELEASE = 'SynthRef release 3'
  REFERENCE_STEM = 'synthetic_SynthRef_r3'
  # Illumina TruSeq read-1 adapter and what follows it, long enough for the
  # shortest simulated insert.
  ADAPTER = 'AGATCGGAAGAGCACACGTCTGAACTCCAGTCACATCTCGTATGCCGTCTTCTGCTTG'
  ADAPTER_TRIM = ADAPTER[0, 34]
  READ_LENGTH = 100

  DEFAULTS = {
    genes: 200,
    de_up: 10,
    de_down: 10,
    replicates: 3,
    reads_per_sample: 100_000,
    adapter_fraction: 0.02,
    permutation_draws: 200
  }.freeze

  # Every draw goes through one of these methods, in program order. Array#shuffle
  # and Array#sample are avoided on purpose: their algorithms are Ruby's to change.
  class Samplers
    def initialize(seed)
      @rng = Random.new(seed)
    end

    def uniform = @rng.rand

    def int(n) = @rng.rand(n)

    # Box-Muller, one value per call (no cached second value to leak state).
    def normal
      u1 = 1.0 - @rng.rand
      u2 = @rng.rand
      Math.sqrt(-2.0 * Math.log(u1)) * Math.cos(2.0 * Math::PI * u2)
    end

    def lognormal(mu, sigma) = Math.exp(mu + (sigma * normal))

    # Marsaglia-Tsang (2000); shape < 1 by the boost u**(1/shape).
    def gamma(shape, scale)
      return gamma(shape + 1.0, scale) * ((1.0 - uniform)**(1.0 / shape)) if shape < 1.0

      d = shape - (1.0 / 3.0)
      c = 1.0 / Math.sqrt(9.0 * d)
      loop do
        x = normal
        v = (1.0 + (c * x))**3
        next if v <= 0.0

        u = 1.0 - uniform
        return d * v * scale if u < 1.0 - (0.0331 * (x**4))
        return d * v * scale if Math.log(u) < (0.5 * x * x) + (d * (1.0 - v + Math.log(v)))
      end
    end

    # Knuth below 10, PTRS (Hörmann 1993, as in numpy) above.
    def poisson(lam)
      return 0 if lam <= 0.0
      return knuth(lam) if lam < 10.0

      ptrs(lam)
    end

    def negative_binomial(mean, dispersion)
      poisson(gamma(1.0 / dispersion, mean * dispersion))
    end

    def fisher_yates!(array)
      (array.length - 1).downto(1) do |i|
        j = int(i + 1)
        array[i], array[j] = array[j], array[i]
      end
      array
    end

    private

    def knuth(lam)
      limit = Math.exp(-lam)
      k = 0
      p = 1.0
      loop do
        p *= uniform
        break if p <= limit

        k += 1
      end
      k
    end

    def ptrs(lam)
      slam = Math.sqrt(lam)
      loglam = Math.log(lam)
      b = 0.931 + (2.53 * slam)
      a = -0.059 + (0.02483 * b)
      invalpha = 1.1239 + (1.1328 / (b - 3.4))
      vr = 0.9277 - (3.6224 / (b - 2.0))
      loop do
        u = uniform - 0.5
        v = uniform
        us = 0.5 - u.abs
        k = (((2.0 * a / us) + b) * u + lam + 0.43).floor
        return k if us >= 0.07 && v <= vr
        next if k.negative? || (us < 0.013 && v > us)

        lhs = Math.log(v) + Math.log(invalpha) - Math.log((a / (us * us)) + b)
        rhs = -lam + (k * loglam) - Math.lgamma(k + 1)[0]
        return k if lhs <= rhs
      end
    end
  end

  Transcript = Struct.new(:id, :gene_id, :sequence, :weight)
  Gene = Struct.new(:id, :abundance, :dispersion, :log2fc, :transcripts)
  Sample = Struct.new(:id, :condition, :target_reads)

  # Reference, expression model and answer key.
  class Model
    BASES = %w[A C G T].freeze

    attr_reader :genes, :samples, :transcripts

    def initialize(rng, cfg)
      @rng = rng
      @cfg = cfg
      @genes = build_genes
      @transcripts = @genes.flat_map(&:transcripts)
      embed_differential_expression
      @samples = build_samples
    end

    def de_genes = @genes.reject { |g| g.log2fc.zero? }

    # Gene-level true counts per sample: negative binomial around the sample's
    # share of each gene, the treated arm scaled by 2**log2fc.
    def true_counts
      @true_counts ||= @samples.to_h do |s|
        weights = @genes.map { |g| g.abundance * (s.condition == 'treated' ? 2.0**g.log2fc : 1.0) }
        total = weights.sum
        counts = @genes.each_with_index.map do |g, i|
          @rng.negative_binomial(s.target_reads * weights[i] / total, g.dispersion)
        end
        [s.id, counts]
      end
    end

    private

    # GC about 45 %: A/T 0.275 each, C/G 0.225 each.
    def base
      u = @rng.uniform
      return 'A' if u < 0.275
      return 'C' if u < 0.500
      return 'G' if u < 0.725

      'T'
    end

    def sequence(length) = Array.new(length) { base }.join

    def isoform_count
      u = @rng.uniform
      return 1 if u < 0.40
      return 2 if u < 0.85

      3
    end

    # Isoform 1 is the whole gene; each further isoform skips one internal
    # stretch of 10-30 %, so isoforms share sequence as real ones do.
    def build_genes
      tx_serial = 0
      (1..@cfg[:genes]).map do |gi|
        gene_id = format('SYN%04d', gi)
        length = @rng.lognormal(Math.log(1500.0), 0.55).round.clamp(500, 5000)
        full = sequence(length)
        seqs = [full]
        (isoform_count - 1).times do
          del = (length * (0.10 + (0.20 * @rng.uniform))).round
          del = [del, length - 500].min
          next if del < 50

          start = 100 + @rng.int([length - del - 200, 1].max)
          seqs << (full[0, start] + full[(start + del)..])
        end
        weights = seqs.map { @rng.gamma(1.0, 1.0) }
        wsum = weights.sum
        txs = seqs.each_with_index.map do |s, k|
          tx_serial += 1
          Transcript.new(format('SYNT%04d.1', tx_serial), gene_id, s, weights[k] / wsum)
        end
        abundance = @rng.lognormal(0.0, 1.2)
        dispersion = @rng.lognormal(Math.log(0.04), 0.5).clamp(0.005, 0.5)
        Gene.new(gene_id, abundance, dispersion, 0.0, txs)
      end
    end

    # 10 up and 10 down among genes at or above the 25th abundance percentile,
    # |log2FC| uniform in [1, 3].
    def embed_differential_expression
      cutoff = @genes.map(&:abundance).sort[@genes.length / 4]
      eligible = @genes.select { |g| g.abundance >= cutoff }
      @rng.fisher_yates!(eligible)
      chosen = eligible.first(@cfg[:de_up] + @cfg[:de_down])
      chosen.each_with_index do |g, i|
        magnitude = 1.0 + (2.0 * @rng.uniform)
        g.log2fc = i < @cfg[:de_up] ? magnitude : -magnitude
      end
    end

    def build_samples
      n = 0
      %w[control treated].flat_map do |cond|
        Array.new(@cfg[:replicates]) do
          n += 1
          target = (@cfg[:reads_per_sample] * (0.8 + (0.4 * @rng.uniform))).round
          Sample.new(format('SYNTH-S%02d', n), cond, target)
        end
      end
    end
  end

  # Single-end reads with a quality profile that falls along the read,
  # substitutions drawn from it, and adapter read-through on short inserts.
  class ReadSimulator
    COMPLEMENT = { 'A' => 'T', 'C' => 'G', 'G' => 'C', 'T' => 'A' }.freeze
    OTHER = { 'A' => %w[C G T], 'C' => %w[A G T], 'G' => %w[A C T], 'T' => %w[A C G] }.freeze

    # Error probability 0.0005 at the first base rising to 0.005 at the last;
    # mean about 0.2 %.
    ERROR = Array.new(READ_LENGTH) { |i| 0.0005 + (0.0045 * ((i / (READ_LENGTH - 1.0))**2)) }.freeze
    QUAL = ERROR.map { |p| (-10.0 * Math.log10(p)).round }.freeze

    def initialize(rng, cfg)
      @rng = rng
      @cfg = cfg
    end

    # Transcript-level counts from the gene counts (categorical by isoform
    # weight), then one read per count, then the file order is shuffled.
    def reads_for(sample, gene_counts, genes)
      picks = []
      genes.each_with_index do |g, gi|
        gene_counts[gi].times { picks << pick_transcript(g) }
      end
      reads = picks.map { |tx| read_from(tx) }
      @rng.fisher_yates!(reads)
      tag = sample.id.delete_prefix('SYNTH-')
      reads.each_with_index.map do |(seq, qual), i|
        "@SYNTH_#{tag}_#{format('%06d', i + 1)}\n#{seq}\n+\n#{qual}\n"
      end
    end

    private

    def pick_transcript(gene)
      u = @rng.uniform
      acc = 0.0
      gene.transcripts.each do |tx|
        acc += tx.weight
        return tx if u < acc
      end
      gene.transcripts.last
    end

    def read_from(tx)
      if @rng.uniform < @cfg[:adapter_fraction]
        insert_len = 50 + @rng.int(50)
        insert = fragment(tx, insert_len)
        raw = insert + ADAPTER[0, READ_LENGTH - insert_len]
      else
        raw = fragment(tx, READ_LENGTH)
      end
      shift = @rng.int(3) - 1
      seq = raw.chars.each_with_index.map do |b, i|
        @rng.uniform < ERROR[i] ? OTHER[b][@rng.int(3)] : b
      end.join
      qual = QUAL.map { |q| (q + shift + 33).chr }.join
      [seq, qual]
    end

    def fragment(tx, length)
      start = @rng.int(tx.sequence.length - length + 1)
      frag = tx.sequence[start, length]
      @rng.uniform < 0.5 ? frag.reverse.tr('ACGT', 'TGCA') : frag
    end
  end

  # Writes the subject, the answer key and the manifest.
  class Generator
    TEMPLATE_DIR = File.expand_path('../templates', __dir__)
    GENERATOR_ROOT = File.expand_path('..', __dir__)

    attr_reader :cfg

    def initialize(seed:, pins:, lock:, out:, **overrides)
      @seed = Integer(seed)
      @pins = pins
      @lock = lock
      @out = out
      @cfg = DEFAULTS.merge(overrides.compact)
    end

    def run
      rng = Samplers.new(@seed)
      model = Model.new(rng, @cfg)
      counts = model.true_counts
      sim = ReadSimulator.new(rng, @cfg)

      subject = File.join(@out, SUBJECT_DIR)
      raise "#{subject} exists; generate into a fresh directory" if File.exist?(subject)

      repo = File.join(subject, 'synthetic_repo')
      write_reference(repo, model)
      model.samples.each do |s|
        write_gzip(File.join(repo, 'data', 'synthetic_reads', "synthetic_#{s.id}.fastq.gz"),
                   sim.reads_for(s, counts[s.id], model.genes).join)
      end
      render_templates(subject, model)
      # The conda-lock output the Dockerfile installs from (§4.3), copied as
      # given so the manifest covers it.
      write(File.join(repo, 'envs', 'rnaseq.lock'), @lock)
      truth = write_truth(model, counts)
      write_manifest(subject, truth)
    end

    private

    def write_reference(repo, model)
      dir = File.join(repo, 'data', 'synthetic_reference')
      fasta = model.transcripts.map do |tx|
        ">#{tx.id} gene=#{tx.gene_id}\n#{tx.sequence.scan(/.{1,60}/).join("\n")}\n"
      end.join
      write(File.join(dir, "#{REFERENCE_STEM}.transcripts.fa"), fasta)
      tx2gene = "transcript_id\tgene_id\n" + model.transcripts.map { |tx| "#{tx.id}\t#{tx.gene_id}\n" }.join
      write(File.join(dir, "#{REFERENCE_STEM}.tx2gene.tsv"), tx2gene)
    end

    # mtime 0 in the gzip header; Ruby's writer keeps 0 as 0 (checked
    # 2026-09-29) and writes OS byte 3. The deflate stream itself depends on
    # the zlib build, which the manifest records.
    def write_gzip(path, text)
      FileUtils.mkdir_p(File.dirname(path))
      File.open(path, 'wb') do |f|
        gz = Zlib::GzipWriter.new(f, Zlib::DEFAULT_COMPRESSION)
        gz.mtime = 0
        gz.write(text)
        gz.finish
      end
      @uncompressed ||= {}
      @uncompressed[path] = Digest::SHA256.hexdigest(text)
    end

    def write(path, text)
      FileUtils.mkdir_p(File.dirname(path))
      File.binwrite(path, text)
    end

    TEMPLATES = {
      'README.md.erb' => 'synthetic_repo/README.md',
      'Snakefile.erb' => 'synthetic_repo/Snakefile',
      'config.yaml.erb' => 'synthetic_repo/config/config.yaml',
      'samples.tsv.erb' => 'synthetic_repo/config/samples.tsv',
      'rnaseq.yml.erb' => 'synthetic_repo/envs/rnaseq.yml',
      'Dockerfile.erb' => 'synthetic_repo/Dockerfile',
      'tximport.R.erb' => 'synthetic_repo/scripts/tximport.R',
      'deseq2.R.erb' => 'synthetic_repo/scripts/deseq2.R',
      'manuscript.md.erb' => 'synthetic_manuscript.md'
    }.freeze

    def render_templates(subject, model)
      ctx = TemplateContext.new(NOTICE, @pins, model, @cfg, @seed)
      TEMPLATES.each do |tpl, rel|
        erb = ERB.new(File.read(File.join(TEMPLATE_DIR, tpl), encoding: 'UTF-8'), trim_mode: '-')
        write(File.join(subject, rel), erb.result(ctx.binding_for_erb))
      end
    end

    def write_truth(model, counts)
      truth = {
        notice: NOTICE,
        purpose: 'Answer key for the self-application subject. Kept outside the subject; ' \
                 'belongs with the expectation table (design §4.2).',
        seed: @seed,
        de_genes: model.de_genes.map { |g| { gene_id: g.id, log2fc: g.log2fc.round(6) } },
        genes: model.genes.map do |g|
          { gene_id: g.id, abundance: g.abundance.round(6), dispersion: g.dispersion.round(6),
            log2fc: g.log2fc.round(6), transcripts: g.transcripts.map { |t| [t.id, t.weight.round(6)] } }
        end,
        samples: model.samples.map do |s|
          { sample: s.id, condition: s.condition, target_reads: s.target_reads,
            realised_reads: counts[s.id].sum, gene_counts: counts[s.id] }
        end
      }
      path = File.join(@out, TRUTH_FILE)
      write(path, "#{JSON.pretty_generate(truth)}\n")
      Digest::SHA256.file(path).hexdigest
    end

    def write_manifest(subject, truth_sha256)
      files = Dir.glob('**/*', File::FNM_DOTMATCH, base: subject)
                 .select { |rel| File.file?(File.join(subject, rel)) }
                 .sort_by(&:b)
                 .map do |rel|
        full = File.join(subject, rel)
        entry = { path: rel, sha256: Digest::SHA256.file(full).hexdigest, size: File.size(full) }
        entry[:uncompressed_sha256] = @uncompressed[full] if @uncompressed&.key?(full)
        entry
      end
      manifest = {
        notice: NOTICE,
        generator: { version: GENERATOR_VERSION, tree_sha256: self.class.generator_tree_sha256,
                     files: self.class.generator_files },
        seed: @seed,
        config: @cfg,
        ruby: RUBY_VERSION, ruby_platform: RUBY_PLATFORM, zlib: Zlib.zlib_version,
        pins_sha256: Digest::SHA256.hexdigest(JSON.generate(@pins)),
        pins_kind: @pins['kind'],
        truth: { path: TRUTH_FILE, sha256: truth_sha256, note: 'outside the subject directory' },
        files: files,
        subject_tree_sha256: Digest::SHA256.hexdigest(files.map { |f| "#{f[:sha256]}  #{f[:path]}\n" }.join)
      }
      path = File.join(subject, 'generator_manifest.json')
      write(path, "#{JSON.pretty_generate(manifest)}\n")
      manifest
    end

    class << self
      # The generator is named by the hash of its own files (lib, templates,
      # bin), listed "<sha256>  <path>" and sorted, like the S-1 record.
      def generator_files
        Dir.glob('{lib,templates,bin}/**/*', base: GENERATOR_ROOT)
           .select { |rel| File.file?(File.join(GENERATOR_ROOT, rel)) }
           .sort_by(&:b)
           .map { |rel| { path: rel, sha256: Digest::SHA256.file(File.join(GENERATOR_ROOT, rel)).hexdigest } }
      end

      def generator_tree_sha256
        Digest::SHA256.hexdigest(generator_files.map { |f| "#{f[:sha256]}  #{f[:path]}\n" }.join)
      end
    end
  end

  # What the templates may read. Kept small so a template cannot reach the
  # answer key by accident: it sees gene and sample ids, never log2fc.
  class TemplateContext
    attr_reader :notice, :pins, :seed, :cfg, :samples, :gene_count, :transcript_count

    def initialize(notice, pins, model, cfg, seed)
      @notice = notice
      @pins = pins
      @seed = seed
      @cfg = cfg
      @samples = model.samples.map { |s| [s.id, s.condition] }
      @gene_count = model.genes.length
      @transcript_count = model.transcripts.length
    end

    def tool(name) = @pins.fetch('tools').fetch(name).fetch('version')

    def conda_spec(name)
      t = @pins.fetch('tools').fetch(name)
      [name, t.fetch('version'), t['build']].compact.join('=')
    end

    def container(rule) = @pins.fetch('rule_containers').fetch(rule)

    def reference_release = REFERENCE_RELEASE
    def reference_stem = REFERENCE_STEM
    def adapter = ADAPTER_TRIM

    def binding_for_erb = binding
  end
end
